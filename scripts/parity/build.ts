import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { createParityRegistry, registryCoverageLine, validateRegistryEvidence } from './registry'

const root = resolve(import.meta.dirname, '../..')
const matrixPath = resolve(root, 'packages/docs/guide/figma-comparison.md')
const registryPath = resolve(root, 'packages/docs/data/figma-capabilities.json')
const reportPath = resolve(root, 'packages/docs/development/parity-report.md')
const write = process.argv.includes('--write')

const source = readFileSync(matrixPath, 'utf8')
const registry = createParityRegistry(matrixPath)
const expectedRegistry = `${JSON.stringify(registry, null, 2)}\n`
const coveragePattern = /^\*\*Coverage:\*\*.*$/m
const coverageLine = registryCoverageLine(registry)
const expectedReport = createReport(registry)
const expectedMatrix = coveragePattern.test(source)
  ? source.replace(coveragePattern, coverageLine)
  : source.replace('::: tip Status Legend', `${coverageLine}\n\n::: tip Status Legend`)

if (write) {
  writeFileSync(matrixPath, expectedMatrix)
  writeFileSync(registryPath, expectedRegistry)
  writeFileSync(reportPath, expectedReport)
  process.stdout.write(`${coverageLine}\n`)
  process.exit(0)
}

const currentRegistry = readFileSync(registryPath, 'utf8')
const currentReport = readFileSync(reportPath, 'utf8')
const failures: string[] = []
failures.push(...validateRegistryEvidence(registry, root))
if (currentRegistry !== expectedRegistry) failures.push('capability registry is stale')
if (currentReport !== expectedReport) failures.push('parity report is stale')
if (source !== expectedMatrix) failures.push('feature-matrix coverage summary is stale')

if (failures.length > 0) {
  process.stderr.write(`${failures.join('; ')}. Run bun run parity:generate.\n`)
  process.exit(1)
}

process.stdout.write(`${coverageLine}\nParity registry is current.\n`)

function createReport(registry: ReturnType<typeof createParityRegistry>): string {
  const categories = new Map<string, typeof registry.capabilities>()
  for (const capability of registry.capabilities) {
    const entries = categories.get(capability.category) ?? []
    entries.push(capability)
    categories.set(capability.category, entries)
  }

  const lines = [
    '# Figma Parity Report',
    '',
    '> Generated by `bun run parity:generate`. Do not edit manually.',
    '',
    registryCoverageLine(registry),
    '',
    `**Evidence-weighted capability confidence:** ${registry.confidenceScore}%`,
    '',
    '| Category | Verified | Supported | Partial | Missing | Total |',
    '| --- | ---: | ---: | ---: | ---: | ---: |'
  ]

  for (const [category, capabilities] of categories) {
    const count = (status: string) => capabilities.filter((item) => item.status === status).length
    lines.push(
      `| ${category} | ${count('verified')} | ${count('supported')} | ${count('partial')} | ${count('missing')} | ${capabilities.length} |`
    )
  }

  const verified = registry.capabilities.filter((capability) => capability.status === 'verified')
  lines.push('', '## Verified capabilities', '')
  for (const capability of verified) {
    lines.push(
      `### ${capability.name}`,
      '',
      `- ID: \`${capability.id}\``,
      `- Acceptance: ${capability.acceptance}`
    )
    for (const evidence of capability.evidence) lines.push(`- Evidence: \`${evidence}\``)
    lines.push('')
  }
  return `${lines.join('\n').trim()}\n`
}
